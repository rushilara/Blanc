"""Render a ``CaseReport`` (``app.reports``) as Markdown (BLA-49).

Pure and deterministic: the same report gives byte-identical Markdown.

**Evidence and model text are untrusted.** Excerpts, answers, claims, labels, locators,
notes and even IDs can contain Markdown or HTML. Nothing from the report is ever emitted
as raw Markdown or HTML:

- Multi-line text (excerpts, investigator notes) goes in a fenced code block whose fence
  is longer than any backtick run in the text, so the text cannot close the fence, and
  renderers show its contents literally (no HTML, links, headings or tables).
- IDs and other short values go in code spans with the same longest-run rule, newlines
  folded to spaces so they cannot start a new block.
- Prose (answers, claims, descriptions, titles) is folded to single lines and every
  character that can start Markdown or HTML structure is backslash-escaped:
  ``\\ ` * _ [ ] < > # + ! | ~ & @``, a leading ``- = >`` or ``1.``, and ``://`` and
  ``www.`` so bare URLs are not turned into links. (Parentheses are left alone: with
  ``[`` and ``]`` escaped they cannot form a link.) Control characters are dropped.

The only structure in the output is what this module writes itself.
"""

from __future__ import annotations

import re
from datetime import UTC, datetime

from app.reports import (
    CaseReport,
    FindingRef,
    ReportAnalysis,
    ReportEvent,
    ReportExclusion,
    ReportNote,
    ReportSource,
)

_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f  ]")
_ALWAYS = re.compile(r"([\\`*_\[\]<>#+!|~&@])")
_LEADING = re.compile(r"^([-=>])")
_ORDERED = re.compile(r"^(\d+)([.)])")
_SCHEME = re.compile(r"://")
_WWW = re.compile(r"(?i)\b(www)\.")
_BACKTICKS = re.compile(r"`+")

_KIND_LABEL = {"claim": "claim", "node": "entity", "edge": "relationship", "event": "event"}
_ROLE_LABEL = {
    "exported": "exported revision",
    "board_active": "board's active revision",
    "board_source": "source of pinned items",
}


def escape_inline(text: str) -> str:
    """One line of literal text: folded whitespace, escaped Markdown/HTML syntax."""
    text = " ".join(_CONTROL.sub("", text).split())
    text = _ALWAYS.sub(r"\\\1", text)
    text = _SCHEME.sub(r":\/\/", text)
    text = _WWW.sub(r"\1\\.", text)
    text = _LEADING.sub(r"\\\1", text)
    return _ORDERED.sub(r"\1\\\2", text)


def escape_paragraphs(text: str) -> list[str]:
    """Literal prose kept as paragraphs (split on blank lines). Each line is escaped on its
    own (so a line cannot start a list, heading or quote) and joined to the next with a
    hard line break (a trailing backslash)."""
    text = _CONTROL.sub("", text.replace("\r\n", "\n").replace("\r", "\n"))
    paragraphs = []
    for paragraph in re.split(r"\n[ \t]*\n", text):
        lines = [escape_inline(line) for line in paragraph.split("\n") if line.strip()]
        if lines:
            paragraphs.append("\\\n".join(lines))
    return paragraphs


def code(text: str) -> str:
    """An inline code span that ``text`` cannot break out of."""
    text = " ".join(_CONTROL.sub("", text).split()) or " "
    runs = [len(run) for run in _BACKTICKS.findall(text)]
    fence = "`" * (max(runs, default=0) + 1)
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{fence}{pad}{text}{pad}{fence}"


def fenced(text: str) -> list[str]:
    """A fenced code block holding ``text`` verbatim (minus control characters)."""
    body = _CONTROL.sub("", text.replace("\r\n", "\n").replace("\r", "\n"))
    runs = [len(run) for run in _BACKTICKS.findall(body)]
    fence = "`" * max(3, max(runs, default=0) + 1)
    return [f"{fence}text", *body.split("\n"), fence]


def _ids(ids: list[str]) -> str:
    return ", ".join(code(i) for i in ids) if ids else "none"


def _ref(ref: FindingRef) -> str:
    return f"{_KIND_LABEL[ref.kind]} {code(ref.ref_id)} (analysis {code(ref.analysis_id)})"


def _pinned(board_item_id: str | None, note_ids: list[str]) -> list[str]:
    lines = []
    if board_item_id is not None:
        lines.append(f"  - Board item: {code(board_item_id)}")
    if note_ids:
        lines.append(f"  - Investigator notes attached: {_ids(note_ids)} (see Investigator notes)")
    return lines


def render_markdown(report: CaseReport) -> str:
    out: list[str] = []
    add = out.append

    add(f"# Case report: {escape_inline(report.case.title)}")
    add("")
    add(
        "> **AI-generated findings for human review.** The answer, claims, relationships "
        "and timeline below were generated by a model from the cited source records. "
        "Nothing in this report has been verified. Read the Limitations section before "
        "relying on any of it."
    )
    add("")

    add("## Report details")
    add("")
    kind = "investigation board" if report.report_kind == "board" else "analysis revision"
    add(f"- Report: {kind} export, report version {code(report.report_version)}")
    add(f"- Case: {escape_inline(report.case.title)} ({code(report.case.case_id)})")
    add(f"- Generated at (UTC): {_utc(report.generated_at)}")
    if report.board is not None:
        board = report.board
        parent = f", parent revision {board.parent_revision}" if board.parent_revision else ""
        add(
            f"- Board: {escape_inline(board.title)} ({code(board.board_id)}), "
            f"revision {board.revision}{parent}, updated {_utc(board.updated_at)}"
        )
        active = code(board.active_analysis_id) if board.active_analysis_id else "none"
        add(f"- Active analysis: {active}")
    for analysis in report.analyses:
        add(f"- Analysis {code(analysis.analysis_id)} ({_ROLE_LABEL[analysis.role]})")
        add(f"  - Parent chain (oldest first): {' -> '.join(code(a) for a in analysis.lineage)}")
    add("")

    add("## Questions and answers")
    add("")
    for analysis in report.analyses:
        _analysis(out, analysis)

    add("## Claims")
    add("")
    add("AI-generated. Status is as saved by the analysis; it is not a verification.")
    add("")
    for claim in report.claims:
        add(f"- **{claim.status}** {escape_inline(claim.text)}")
        add(f"  - Claim {code(claim.claim_id)} from analysis {code(claim.analysis_id)}")
        add(f"  - Sources: {_ids(claim.evidence_ids)}")
        out.extend(_pinned(claim.board_item_id, claim.note_ids))
    if not report.claims:
        add("None.")
    add("")

    add("## Entities")
    add("")
    add("AI-generated graph nodes. Two nodes with similar names are not merged.")
    add("")
    for entity in report.entities:
        add(f"- {escape_inline(entity.label)} ({escape_inline(entity.type)})")
        add(f"  - Node {code(entity.node_id)} from analysis {code(entity.analysis_id)}")
        add(f"  - Sources: {_ids(entity.evidence_ids)}")
        out.extend(_pinned(entity.board_item_id, entity.note_ids))
    if not report.entities:
        add("None.")
    add("")

    add("## Relationships")
    add("")
    add("AI-generated graph edges, source -> target. Status is as saved; not a verification.")
    add("")
    for edge in report.relationships:
        source = escape_inline(edge.source.label or edge.source.node_id)
        target = escape_inline(edge.target.label or edge.target.node_id)
        add(f"- **{edge.status}** {source} -> {target}: {escape_inline(edge.type)}")
        add(
            f"  - Edge {code(edge.edge_id)} from analysis {code(edge.analysis_id)}: "
            f"{code(edge.source.node_id)} -> {code(edge.target.node_id)}"
        )
        if edge.description:
            add(f"  - Description: {escape_inline(edge.description)}")
        add(f"  - Sources: {_ids(edge.evidence_ids)}")
        out.extend(_pinned(edge.board_item_id, edge.note_ids))
    if not report.relationships:
        add("None.")
    add("")

    add("## Timeline")
    add("")
    add(
        "AI-generated events. Times are shown at the precision the sources support; "
        "nothing is made more precise than written."
    )
    add("")
    add("### Dated events (normalized order)")
    add("")
    _events(out, report.timeline.dated)
    add("### Uncertain times (order not established)")
    add("")
    add("Approximate times, or exact times with no known time zone.")
    add("")
    _events(out, report.timeline.uncertain)
    add("### Undated events")
    add("")
    _events(out, report.timeline.undated)

    add("## Sources")
    add("")
    add("Every record cited above, once. Excerpts are exact text from the record, shown literally.")
    add("")
    for source in report.sources:
        _source(out, source)
    if not report.sources:
        add("None.")
        add("")

    add("## Excluded evidence")
    add("")
    add(
        "These records were excluded from the analysis named on each line. They support "
        "nothing in this report, and their content is not shown. Excluding a record "
        "changes what the analysis can conclude, not what happened."
    )
    add("")
    for exclusion in report.excluded_evidence:
        _exclusion(out, exclusion)
    if not report.excluded_evidence:
        add("None.")
    add("")

    add("## Investigator notes")
    add("")
    add(
        "Written by the investigator, not by the model. Notes are not evidence and are "
        "kept separate from AI-generated text."
    )
    add("")
    for note in report.investigator_notes:
        _note(out, note)
    if not report.investigator_notes:
        if report.report_kind == "analysis":
            add("None. Notes live on boards; export a board to include them.")
        else:
            add("None.")
        add("")

    add("## Limitations")
    add("")
    for limitation in report.limitations:
        add(f"- {escape_inline(limitation)}")
    add("")
    return "\n".join(out)


def _utc(moment: datetime) -> str:
    return moment.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _analysis(out: list[str], analysis: ReportAnalysis) -> None:
    add = out.append
    add(f"### Analysis {code(analysis.analysis_id)}")
    add("")
    add(f"- Question: {escape_inline(analysis.question)}")
    add(f"- Saved at (UTC): {_utc(analysis.created_at)}")
    add(f"- Records retrieved: {len(analysis.retrieved_record_ids)}")
    add(f"- Records excluded: {_ids(analysis.excluded_record_ids)}")
    add("")
    if analysis.needs_review:
        add(
            "> **Needs review.** This revision failed validation after one retry and holds "
            "a partial result."
        )
        add("")
    add("Answer (AI-generated):")
    add("")
    paragraphs = escape_paragraphs(analysis.answer)
    for paragraph in paragraphs:
        add(paragraph)
        add("")
    if not paragraphs:
        add("No answer was saved.")
        add("")
    if analysis.unresolved_questions:
        add("Unresolved questions (AI-generated):")
        add("")
        for question in analysis.unresolved_questions:
            add(f"- {escape_inline(question)}")
        add("")


def _events(out: list[str], events: list[ReportEvent]) -> None:
    add = out.append
    for event in events:
        when = escape_inline(event.display) if event.display else "no usable timestamp"
        add(f"- {when} ({event.precision}) **{event.status}** {escape_inline(event.description)}")
        add(f"  - Event {code(event.event_id)} from analysis {code(event.analysis_id)}")
        written = code(event.timestamp) if event.timestamp is not None else "none"
        no_zone = event.precision == "exact" and not event.timezone_known
        zone = ", time zone unknown (shown as written)" if no_zone else ""
        add(f"  - Timestamp as written: {written}, kind {event.timestamp_kind or 'unknown'}{zone}")
        add(f"  - Sources: {_ids(event.evidence_ids)}")
        out.extend(_pinned(event.board_item_id, event.note_ids))
    if not events:
        add("None.")
    add("")


def _source(out: list[str], source: ReportSource) -> None:
    add = out.append
    add(f"### Source {code(source.record_id)}")
    add("")
    add(f"- File: {code(source.source_file)}")
    add(f"- Locator: {code(source.source_locator)}")
    stamp = code(source.timestamp) if source.timestamp is not None else "none"
    add(f"- Timestamp: {stamp} ({source.timestamp_kind or 'unknown'})")
    add(f"- Cited by: {', '.join(_ref(ref) for ref in source.cited_by)}")
    if source.excluded_in:
        add(
            f"- Excluded in analysis {_ids(source.excluded_in)}: it supports nothing there; "
            "it is cited here only by items from a revision that still included it."
        )
    excerpt = source.excerpt
    cut = f", truncated from {excerpt.content_chars}" if excerpt.truncated else ""
    add(f"- Excerpt (characters {excerpt.char_start}-{excerpt.char_end}{cut}):")
    add("")
    out.extend(fenced(excerpt.text))
    add("")


def _exclusion(out: list[str], exclusion: ReportExclusion) -> None:
    how = (
        f"inherited from {code(exclusion.first_excluded_in)}"
        if exclusion.inherited
        else "excluded in this revision"
    )
    where = (
        f"{code(exclusion.source_file)} at {code(exclusion.source_locator)}"
        if exclusion.source_file is not None and exclusion.source_locator is not None
        else "record not found in the case database"
    )
    out.append(
        f"- EXCLUDED {code(exclusion.record_id)} from analysis {code(exclusion.analysis_id)} "
        f"({how}): {where}"
    )


def _note(out: list[str], note: ReportNote) -> None:
    add = out.append
    add(f"### Note {code(note.note_id)}")
    add("")
    add(f"- Author: {escape_inline(note.author)}")
    add(f"- Added at (UTC): {_utc(note.created_at)}")
    if note.target is not None:
        add(f"- Attached to: {_ref(note.target)}, board item {code(note.target_item_id or '')}")
    else:
        add("- Attached to: the board as a whole")
    add("")
    out.extend(fenced(note.text))
    add("")
